#!/bin/bash
# Проверка версии ядра на подверженность CVE-2022-0847 (Dirty Pipe).
# Уязвимы: 5.8 <= ver, исправлено в 5.10.102 / 5.15.25 / 5.16.11.
# Только обнаружение, без эксплуатации.
check() {
  local v=$1; IFS=. read -r a b c <<<"${v%%-*}"; c=${c:-0}
  local n=$((a*1000000+b*1000+c))
  if   (( n < 5008000 )); then echo "$v: НЕ подвержено (ядро старше 5.8)"
  elif (( n < 5010102 )); then echo "$v: УЯЗВИМО (нужно >= 5.10.102)"
  elif (( n < 5011000 )); then echo "$v: исправлено (ветка 5.10)"
  elif (( n < 5015025 )); then echo "$v: УЯЗВИМО (нужно >= 5.15.25)"
  elif (( n < 5016000 )); then echo "$v: исправлено (ветка 5.15)"
  elif (( n < 5016011 )); then echo "$v: УЯЗВИМО (нужно >= 5.16.11)"
  else echo "$v: исправлено (>= 5.16.11)"; fi
}
echo "=== Проверка Dirty Pipe (CVE-2022-0847) ==="
echo "Текущее ядро:"
check "$(uname -r)"
if [ "$#" -gt 0 ]; then
  echo; echo "Тестовые версии:"; for v in "$@"; do check "$v"; done
fi
